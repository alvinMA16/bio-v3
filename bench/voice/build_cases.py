def build():
    cases=[]
    for family,split,items in FAMILIES:
        for i,(title,history,expectation,tags) in enumerate(items):
            cases.append({'id':f'{family}-{i+1:02}', 'family':family, 'split':split,
                'source_kind':'observed_pattern_rewrite' if i==0 else 'derived_stress_variant',
                'title':title,'messages':[{'role':role,'content':content} for role,content in history],
                'rubric':{'expectation':expectation,'focus':tags},
                'provenance':'2026-09-07 readonly review; de-identified rewrite, not verbatim replay'})
    return cases

